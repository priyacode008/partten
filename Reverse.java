
public class Reverse{
    public static void main(String [] args){
        
        int n=5,i,j;
        
        System.out.println("the matrix format:");
        for(i=0;i<=n;i++){
            for(j=i;j<=n;j++){
                System.out.print("*");
            }
            System.out.println(" ");
        }
    }
}